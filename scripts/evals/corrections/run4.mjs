#!/usr/bin/env node
// Correction eval, round 4 (Nov 4): conservative, label-aware swap retrieval, independent same-medium
// discovery and a Surprise novelty source, on round 3's retrieval stand-in. Free: no network, no model, no
// production change. Deterministic.
//
//   node scripts/evals/corrections/run4.mjs                 # writes reports/round4.md and round4.json
//   node scripts/evals/corrections/run4.mjs --out <dir>
//
// Same cases, rounds, gates and evaluation as round 3 (run3.mjs); round 3's baseline and swap arms are
// included unchanged for comparison. The rules are in patterns.mjs; retrieval options in retrieval.mjs.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { GATES3, LIMITATIONS3, ROUND3_ARMS, markOf, runEval3 } from "./run3.mjs";
import { STRENGTHS } from "./run.mjs";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const A = { strength: STRENGTHS[0], split: true, anchorOff: true, retrieval: "local" };
const P = { r4: true, select: "production" };
const SURPRISE = { bridge: true, surprise: true, labelCut: true };
const FULL = { fetch: "swap", conservative: true, reorder: "guarded", discovery: true };

export const ROUND4_ARMS = [
  ROUND3_ARMS[0],                                                     // current retrieval, production selection
  ROUND3_ARMS[2],                                                     // round 3's swap, production selection
  { id: "conservative swap", ...P, fetch: "swap", conservative: true },
  { id: "conservative swap + label reorder", ...P, fetch: "swap", conservative: true, reorder: "guarded" },
  { id: "conservative swap + label reorder (unguarded labels)", ...P, fetch: "swap", conservative: true, reorder: "unguarded" },
  { id: "discovery + label reorder (no swap)", ...P, fetch: "current", reorder: "guarded", discovery: true },
  { id: "conservative swap + label reorder + discovery", ...P, ...FULL },
  { id: "... + Surprise novelty", ...P, ...FULL, ...SURPRISE },
  { id: "conservative swap + label reorder + Surprise novelty (no discovery)", ...P, fetch: "swap", conservative: true, reorder: "guarded", ...SURPRISE },
  { id: "... + Surprise novelty + A", r4: true, ...A, ...FULL, ...SURPRISE },
  { id: "oracle: ... + Surprise novelty / true supports", ...P, ...FULL, ...SURPRISE, supportsKey: "trueSupports", oracle: true }
];

const EXAMPLE_ARMS = ["current retrieval / production selection", "swap / production selection", "conservative swap + label reorder", "conservative swap + label reorder + Surprise novelty (no discovery)", "... + Surprise novelty"];
const EXAMPLES = [
  ["example-paige", "not me: ai-genre-fantasy-mythic-worlds"],
  ["example-paige", "not me: every pattern behind the Surprise anchor (ai-uncanny-mystery-tv)"],
  ["dislikes-50", "not me: horror-anywhere"],
  ["split-50", "not me: fantasy-books"],
  ["broad-50", "not in movies: thrillers"],
  ["narrow-100", "not me: sci-fi-films"]
];

export function reportMarkdown4(run) {
  const L = [];
  L.push("# Correction eval, round 4: conservative swap, discovery and Surprise novelty", "");
  L.push("Generated by `node scripts/evals/corrections/run4.mjs`. No network, no model calls, no production change. Deterministic. Same retrieval stand-in, cases, rounds and gates as round 3.", "");
  L.push(`- Stand-in selection matches production's on every case and round: **${run.parity ? "yes" : "NO"}**; fallback shows the shortlist: **${run.fallbackMismatches ? "NO" : "yes"}**`, "");
  L.push("## Gates (round 1's where they apply, and the provisional revisions)", "");
  const ids = Object.keys(GATES3);
  L.push(`| Arm | ${ids.join(" | ")} |`, `|---|${ids.map(() => "---").join("|")}|`);
  for (const r of run.results) L.push(`| ${r.arm} | ${ids.map((g) => markOf(r.gates[g])).join(" | ")} |`);
  L.push("", "## Corrections, evidence and cost", "");
  L.push("\"Not me\" titles: mostly (>=50%) from the rejected pattern's true supporting items. Rejected kind: the title's own catalog labels match the rejected pattern's (guarded, true supports), whatever its supports; catches titles like Unfinished Tales that support lists miss. Other-pattern titles: current retrieval's titles mostly from a pattern that wasn't rejected. Valid anchors lost: anchors current retrieval used that truly support a pattern that wasn't rejected. Support-sensitive: share of evaluations whose anchors or pool change when the stored supports are replaced by the true ones (what a profile refresh that fixes supports would change).", "");
  L.push("| Arm | \"Not me\" titles | Rejected kind (\"not me\") | Rejected kind (all rejections) | Replaceable in pool (of current's \"not me\" titles) | Replaced (of replaceable) | Rejected medium still served | Other-pattern titles kept | Endorsed kept | Wrong-support kept | Valid anchors lost | Support-sensitive | From discovery in six (relevant) | Calls (current → arm) | Extra wave |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
  for (const r of run.results) {
    const n = r.numbers, x = n.r4;
    L.push(`| ${r.arm} | ${n.notMeBase} → ${n.notMeArm} | ${x.kindBase} → ${x.kindArm} | ${x.kindBaseAll} → ${x.kindArmAll} | ${n.supplyArm.replaceable ?? 0} | ${n.replacedOfReplaceable}/${n.replaceableInArmPool} | ${n.servedBase} → ${n.servedArm} (of ${n.rejectedMedia}) | ${x.otherKept}/${x.otherBase} | ${n.endorsedKept}/${n.endorsedBase} | ${n.wrongKept}/${n.wrongBase} | ${x.lostValidAnchors} (of ${x.lostAnchors} lost) | ${x.supportSensitive ?? "–"}% | ${x.discoveryInSix} (${x.discoveryRelevant}) | ${n.callsBase} → ${n.callsArm} | ${n.extraWave}% |`);
  }
  L.push("", "## Diversity, relevance and set size", "");
  L.push("| Arm | Unrelated kept | Lost a medium | 3+ of one medium | Creator duplicates | Unrelated pairs in order | Score drop | Corrected fit | Sets under six (current → arm; smaller / larger) |", "|---|---|---|---|---|---|---|---|---|");
  for (const r of run.results) {
    const n = r.numbers;
    L.push(`| ${r.arm} | ${n.unrelatedKept}/${n.unrelatedBase} | ${n.lostMedium}/${n.rejecting} | ${n.concentratedBase}% → ${n.concentratedArm}% | ${n.creatorDupes} | ${n.concordance}% | ${n.scoreDrop}% | ${n.judgeGain}% | ${n.shortBase} → ${n.shortArm} (${n.smaller} / ${n.larger}) |`);
  }
  L.push("", "## Surprise Me", "");
  L.push("| Arm | Offered (current → arm) | Mostly from a rejection | Rejected kind | Lost (of evaluations with one) | Not from a Liked rating | Top similarity (lower = more novel) |", "|---|---|---|---|---|---|---|");
  for (const r of run.results) {
    const n = r.numbers, x = n.r4;
    L.push(`| ${r.arm} | ${n.edgeBase}% → ${n.edgeArm}% | ${n.edgeNegBase} → ${n.edgeNegArm} | ${x.edgeKindBase} → ${x.edgeKindArm} | ${n.edgeLost}/${n.edgeEvaluations} | ${n.edgeNotLiked} | ${n.edgeSimBase} → ${n.edgeSimArm} |`);
  }
  L.push("", "## Worked examples (round 1)", "");
  for (const e of run.examples) {
    L.push(`### ${e.case}: ${e.scenario}`, "", `Current retrieval offers: ${e.production.join(" · ")}`, "");
    for (const r of e.rows) {
      L.push(`- **${r.arm}** (${r.calls} calls; anchors: ${r.anchors.join(", ")}): ${r.six.join(" · ")}`);
      for (const x of r.targets) L.push(`  - ${x}`);
    }
    L.push("");
  }
  L.push("## Gate definitions", "");
  for (const [id, text] of Object.entries(GATES3)) L.push(`- **${id}**: ${text}`);
  L.push("", "## Limitations", "");
  for (const l of [...LIMITATIONS3, ...LIMITATIONS4]) L.push(`- ${l}`);
  return L.join("\n") + "\n";
}

export const LIMITATIONS4 = [
  "Labels come from production's cross-medium label map. Stored games carry no IGDB themes, so no game can be confirmed as a rejected kind: the conservative rule never drops a game anchor, and label reordering never moves a game. Storing IGDB themes would change that.",
  "Discovery and the Surprise bridge read snapshot shelves in a fixed pseudo-random order; real browse results come in the provider's popularity order.",
  "\"Rejected kind\" uses the same label rule some arms use to act, so arms using labels are partly graded by their own rule; the support-based \"not me\" count is the independent measure."
];

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const at = process.argv.indexOf("--out");
  const dir = at > 0 ? process.argv[at + 1] : join(HERE, "reports");
  const run = await runEval3({ arms: ROUND4_ARMS, exampleArms: EXAMPLE_ARMS, examples: EXAMPLES });
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "round4.json"), JSON.stringify(run, null, 1) + "\n");
  writeFileSync(join(dir, "round4.md"), reportMarkdown4(run));
  console.log(`wrote ${join(dir, "round4.md")}`);
  for (const r of run.results) console.log(`${r.arm}: failed ${Object.entries(r.gates).filter(([, g]) => g === false).map(([k]) => k).join(", ") || "none"}`);
}
